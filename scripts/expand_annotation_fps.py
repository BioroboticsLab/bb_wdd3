"""
Expand resolution-tier annotation rows (data/raw/annotations_resolution_expanded.csv)
into fps-variant rows (ds30fps, ds15fps), reusing prepare_training_data.py's
create_downsampled_annotations() so the new data follows the exact same
fps-downsampling convention already used for the rest of the dataset
(verified against the real fps_multires_clean.csv before building this).

Requires the ds30fps/ds15fps video files to already exist in data/videos/
(generated by integrate_raw_videos.py) -- their actual frame counts are
used to clamp each window to valid video bounds, exactly as
prepare_training_data.py does.

Usage:
    python scripts/expand_annotation_fps.py
"""
import os
import sys

import cv2
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from prepare_training_data import create_downsampled_annotations

INPUT_PATH = "./data/raw/annotations_resolution_expanded.csv"
OUTPUT_PATH = "./data/raw/annotations_fps_expanded.csv"
OUT_VIDEO_DIR = "./data/videos"

# Native source fps is 60 for this batch; matches the factors
# prepare_training_data.py uses for its own ds30fps/ds15fps generation.
FPS_FACTORS = {30: 2, 15: 4}


def get_frame_count(path):
    cap = cv2.VideoCapture(path)
    n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    cap.release()
    return n


def expand_fps(df):
    out_rows = [df]
    missing_videos = set()

    for video_name in df["video_name"].unique():
        base_name = video_name.replace(".mp4", "")
        for target_fps, factor in FPS_FACTORS.items():
            dst_video = f"{base_name}_ds{target_fps}fps.mp4"
            dst_path = os.path.join(OUT_VIDEO_DIR, dst_video)
            if not os.path.exists(dst_path):
                missing_videos.add(dst_video)
                continue

            n_frames = get_frame_count(dst_path)
            new_rows = create_downsampled_annotations(
                df, video_name, dst_video, factor=factor,
                video_frame_count=n_frames,
            )
            out_rows.append(new_rows)

    if missing_videos:
        print(f"WARNING: {len(missing_videos)} fps-variant video(s) not found in "
              f"{OUT_VIDEO_DIR}, skipped:")
        for v in sorted(missing_videos):
            print(f"  - {v}")

    return pd.concat(out_rows, ignore_index=True)


def main():
    df = pd.read_csv(INPUT_PATH)
    expanded = expand_fps(df)
    expanded.to_csv(OUTPUT_PATH, index=False)
    print(f"{len(df)} native-fps rows -> {len(expanded)} rows "
          f"(native + {len(FPS_FACTORS)} fps variants)")
    print(f"Saved to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
